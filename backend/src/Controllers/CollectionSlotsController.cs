        /// <summary>
        /// Retrieves bookings.
        /// scope = 'upcoming': Bookings from Today onwards (upcoming appointments).
        /// scope = 'past': Historical records from dates prior to Today (permanently preserved).
        /// scope = 'all': All bookings.
        /// </summary>
        [HttpGet("bookings")]
        [AllowAnonymous]
        public async Task<IActionResult> GetBookings([FromQuery] string? department, [FromQuery] string? scope)
        {
            var bookings = new List<object>();
            var conn = _context.Database.GetDbConnection();
            bool wasClosed = conn.State == ConnectionState.Closed;

            try
            {
                if (wasClosed) await conn.OpenAsync();
                await EnsureTablesAndHolidaysAsync(conn);

                using var queryCmd = conn.CreateCommand();

                string dateFilter = "";
                string orderClause = "ORDER BY \"CreatedAt\" DESC";

                if (string.Equals(scope, "upcoming", StringComparison.OrdinalIgnoreCase))
                {
                    dateFilter = "AND \"BookedDate\" >= (NOW() AT TIME ZONE 'Asia/Colombo')::date";
                    orderClause = "ORDER BY \"BookedDate\" ASC, \"BookedSlotTime\" ASC";
                }
                else if (string.Equals(scope, "past", StringComparison.OrdinalIgnoreCase))
                {
                    dateFilter = "AND \"BookedDate\" < (NOW() AT TIME ZONE 'Asia/Colombo')::date";
                    orderClause = "ORDER BY \"BookedDate\" DESC, \"CreatedAt\" DESC";
                }

                queryCmd.CommandText = @"
                    SELECT ""Id"", COALESCE(""ApplicationCode"", CAST(""ApplicationId"" AS varchar)), ""CitizenNic"", 
                           COALESCE(""DepartmentName"", 'General'), COALESCE(""ServiceName"", 'Document Collection'), 
                           COALESCE(CAST(""BookedDate"" AS varchar), ''), COALESCE(""BookedSlotTime"", ''), ""Status"", 
                           COALESCE(""ConfirmationCode"", 'SL-APT-0000'), COALESCE(""PreferredTimes"", ''), ""CreatedAt"",
                           CASE WHEN ""BookedDate"" < (NOW() AT TIME ZONE 'Asia/Colombo')::date THEN TRUE ELSE FALSE END AS ""IsPast""
                    FROM ""CollectionBookings""
                    WHERE (@dept IS NULL OR LOWER(""DepartmentName"") LIKE LOWER(@dept))
                      " + dateFilter + @"
                    " + orderClause + @"
                    LIMIT 200;
                ";

                var p = queryCmd.CreateParameter();
                p.ParameterName = "@dept";
                p.DbType = DbType.String;
                p.Value = string.IsNullOrWhiteSpace(department) || department == "All" ? DBNull.Value : $"%{department.Trim()}%";
                queryCmd.Parameters.Add(p);

                using var reader = await queryCmd.ExecuteReaderAsync();
                while (await reader.ReadAsync())
                {
                    bookings.Add(new
                    {
                        id = reader.GetInt32(0),
                        applicationCode = reader.GetString(1),
                        citizenNic = reader.GetString(2),
                        departmentName = reader.GetString(3),
                        serviceName = reader.GetString(4),
                        bookedDate = reader.GetString(5),
                        bookedSlotTime = reader.GetString(6),
                        status = reader.GetString(7),
                        confirmationCode = reader.GetString(8),
                        preferredTimes = reader.GetString(9),
                        createdAt = reader.GetDateTime(10),
                        isPast = reader.GetBoolean(11)
                    });
                }
            }
            catch (Exception ex)
            {
                return StatusCode(500, $"Database Error: {ex.Message}");
            }
            finally
            {
                if (wasClosed) await conn.CloseAsync();
            }

            return Ok(bookings);
        }

        // Another slot of the same department on the same day/date whose hours overlap [start, end)
        private async Task<string?> FindOverlappingSlotAsync(string department, int dayOfWeek, string? specificDate, string start, string end, int? excludeId)
        {
            if (!string.IsNullOrWhiteSpace(specificDate))
            {
                return await _context.Database.SqlQueryRaw<string>(@"
                    SELECT SUBSTRING(CAST(""StartTime"" AS varchar) FROM 1 FOR 5) || ' - ' || SUBSTRING(CAST(""EndTime"" AS varchar) FROM 1 FOR 5) AS ""Value""
                    FROM ""CollectionTimeSlots""
                    WHERE LOWER(""DepartmentName"") = LOWER({0}) AND ""SpecificDate"" = {1}::date
                      AND ""StartTime"" < {3}::time AND ""EndTime"" > {2}::time
                      AND ""Id"" <> {4}
                    LIMIT 1", department.Trim(), specificDate, start, end, excludeId ?? 0)
                    .FirstOrDefaultAsync();
            }

            return await _context.Database.SqlQueryRaw<string>(@"
                SELECT SUBSTRING(CAST(""StartTime"" AS varchar) FROM 1 FOR 5) || ' - ' || SUBSTRING(CAST(""EndTime"" AS varchar) FROM 1 FOR 5) AS ""Value""
                FROM ""CollectionTimeSlots""
                WHERE LOWER(""DepartmentName"") = LOWER({0}) AND ""DayOfWeek"" = {1} AND ""SpecificDate"" IS NULL
                  AND ""StartTime"" < {3}::time AND ""EndTime"" > {2}::time
                  AND ""Id"" <> {4}
                LIMIT 1", department.Trim(), dayOfWeek, start, end, excludeId ?? 0)
                .FirstOrDefaultAsync();
        }

        [HttpPost]
        public async Task<IActionResult> CreateSlot([FromBody] CollectionTimeSlotDto dto)
        {
            if (string.IsNullOrWhiteSpace(dto.DepartmentName))
                return BadRequest(ValidationError.Body("Department is required for collection slots.", "departmentName"));

            int dow = dto.DayOfWeek;
            if (!string.IsNullOrWhiteSpace(dto.SpecificDate) && DateTime.TryParse(dto.SpecificDate, out var specDate))
            {
                dow = (int)specDate.DayOfWeek == 0 ? 7 : (int)specDate.DayOfWeek;
            }

            var overlap = await FindOverlappingSlotAsync(dto.DepartmentName, dow, dto.SpecificDate, dto.StartTime!, dto.EndTime!, null);
            if (overlap != null)
                return BadRequest(ValidationError.Body($"This time overlaps the existing {overlap} slot.", "startTime"));

            var sql = @"
                INSERT INTO ""CollectionTimeSlots"" 
                (""DayOfWeek"", ""StartTime"", ""EndTime"", ""MaxCapacity"", ""IsActive"", ""DepartmentName"", ""DepartmentId"", ""SpecificDate"") 
                VALUES ({0}, {1}::time, {2}::time, {3}, {4}, {5}, {6}, {7}::date);
            ";
            await _context.Database.ExecuteSqlRawAsync(sql, dow, dto.StartTime, dto.EndTime, dto.MaxCapacity, dto.IsActive, dto.DepartmentName, dto.DepartmentId, dto.SpecificDate);
            
            return Ok(new { message = "Time slot created successfully for " + dto.DepartmentName });
        }

        [HttpPut("{id}")]
        public async Task<IActionResult> UpdateSlot(int id, [FromBody] CollectionTimeSlotDto dto)
        {
            var department = string.IsNullOrWhiteSpace(dto.DepartmentName)
                ? await _context.Database.SqlQueryRaw<string>(
                    @"SELECT ""DepartmentName"" AS ""Value"" FROM ""CollectionTimeSlots"" WHERE ""Id"" = {0}", id).FirstOrDefaultAsync()
                : dto.DepartmentName;
            if (department == null)
                return NotFound(ValidationError.Body("Time slot not found."));

            int dow = dto.DayOfWeek;
            if (!string.IsNullOrWhiteSpace(dto.SpecificDate) && DateTime.TryParse(dto.SpecificDate, out var specDate))
            {
                dow = (int)specDate.DayOfWeek == 0 ? 7 : (int)specDate.DayOfWeek;
            }

            var overlap = await FindOverlappingSlotAsync(department, dow, dto.SpecificDate, dto.StartTime!, dto.EndTime!, id);
            if (overlap != null)
                return BadRequest(ValidationError.Body($"This time overlaps the existing {overlap} slot.", "startTime"));

            var sql = @"
                UPDATE ""CollectionTimeSlots"" 
                SET ""DayOfWeek"" = {0}, ""StartTime"" = {1}::time, ""EndTime"" = {2}::time, 
                    ""MaxCapacity"" = {3}, ""IsActive"" = {4}, ""DepartmentName"" = COALESCE({5}, ""DepartmentName""), 
                    ""DepartmentId"" = {6}, ""SpecificDate"" = {7}::date
                WHERE ""Id"" = {8};
            ";
            await _context.Database.ExecuteSqlRawAsync(sql, dow, dto.StartTime, dto.EndTime, dto.MaxCapacity, dto.IsActive, dto.DepartmentName, dto.DepartmentId, dto.SpecificDate, id);
            
            return Ok(new { message = "Time slot updated." });
        }

