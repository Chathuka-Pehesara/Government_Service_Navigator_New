        [HttpPost("holidays")]
        public async Task<IActionResult> AddHoliday([FromBody] CreateHolidayDto dto)
        {
            if (string.IsNullOrWhiteSpace(dto.DepartmentName))
                return BadRequest(ValidationError.Body("Department is required.", "departmentName"));
            if (!DateTime.TryParse(dto.HolidayDate, out var holDate))
                return BadRequest(ValidationError.Body("Valid holiday date is required (yyyy-MM-dd).", "holidayDate"));

            var conn = _context.Database.GetDbConnection();
            bool wasClosed = conn.State == ConnectionState.Closed;

            try
            {
                if (wasClosed) await conn.OpenAsync();
                await EnsureTablesAndHolidaysAsync(conn);

                using var cmd = conn.CreateCommand();
                cmd.CommandText = @"
                    INSERT INTO ""DepartmentHolidays"" (""DepartmentName"", ""HolidayDate"", ""Reason"")
                    VALUES (@dept, @hDate, @reason)
                    ON CONFLICT (LOWER(""DepartmentName""), ""HolidayDate"") 
                    DO UPDATE SET ""Reason"" = EXCLUDED.""Reason"";
                ";
                var pDept = cmd.CreateParameter(); pDept.ParameterName = "@dept"; pDept.Value = dto.DepartmentName.Trim(); cmd.Parameters.Add(pDept);
                var pDate = cmd.CreateParameter(); pDate.ParameterName = "@hDate"; pDate.Value = holDate.Date; cmd.Parameters.Add(pDate);
                var pReason = cmd.CreateParameter(); pReason.ParameterName = "@reason"; pReason.Value = string.IsNullOrWhiteSpace(dto.Reason) ? "Public Holiday" : dto.Reason.Trim(); cmd.Parameters.Add(pReason);

                await cmd.ExecuteNonQueryAsync();
                return Ok(new { message = $"Date {holDate:yyyy-MM-dd} successfully declared as holiday for {dto.DepartmentName}." });
            }
            catch (Exception ex)
            {
                return StatusCode(500, $"Database Error: {ex.Message}");
            }
            finally
            {
                if (wasClosed) await conn.CloseAsync();
            }
        }

