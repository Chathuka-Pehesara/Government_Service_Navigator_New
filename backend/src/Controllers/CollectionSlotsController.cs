        /// <summary>
        /// Real-time Daily Schedule starting from Today onwards.
        /// Past dates automatically disappear from this view.
        /// Each day includes full time ranges, capacity, live bookings, real-time active indicators, and holiday status.
        /// </summary>
        [HttpGet("daily-schedule")]
        [AllowAnonymous]
        public async Task<IActionResult> GetDailySchedule([FromQuery] string? department, [FromQuery] int days = 14)
        {
            if (days < 1) days = 1;
            if (days > 60) days = 60;

            var conn = _context.Database.GetDbConnection();
            bool wasClosed = conn.State == ConnectionState.Closed;

            try
            {
                if (wasClosed) await conn.OpenAsync();
                await EnsureTablesAndHolidaysAsync(conn);

                // Fetch current date & time in Sri Lanka timezone
                using var nowCmd = conn.CreateCommand();
                nowCmd.CommandText = @"SELECT (NOW() AT TIME ZONE 'Asia/Colombo')::date, CAST((NOW() AT TIME ZONE 'Asia/Colombo')::time AS varchar)";
                using var nowReader = await nowCmd.ExecuteReaderAsync();
                await nowReader.ReadAsync();
                DateTime today = nowReader.GetDateTime(0);
                string timeStr = nowReader.GetString(1);
                TimeSpan currentTime = TimeSpan.TryParse(timeStr, out var parsedT) ? parsedT : TimeSpan.Zero;
                await nowReader.CloseAsync();

                DateTime endDate = today.AddDays(days - 1);

                // Fetch declared holidays for department in range [today, endDate]
                var holidays = new Dictionary<string, (int id, string reason)>();
                using var holCmd = conn.CreateCommand();
                holCmd.CommandText = @"
                    SELECT ""Id"", CAST(""HolidayDate"" AS varchar), ""Reason""
                    FROM ""DepartmentHolidays""
                    WHERE ""HolidayDate"" >= @today AND ""HolidayDate"" <= @endDate
                      AND (@dept IS NULL OR LOWER(""DepartmentName"") LIKE LOWER(@dept))";
                var pHolToday = holCmd.CreateParameter(); pHolToday.ParameterName = "@today"; pHolToday.Value = today; holCmd.Parameters.Add(pHolToday);
                var pHolEnd = holCmd.CreateParameter(); pHolEnd.ParameterName = "@endDate"; pHolEnd.Value = endDate; holCmd.Parameters.Add(pHolEnd);
                var pHolDept = holCmd.CreateParameter(); pHolDept.ParameterName = "@dept"; 
                pHolDept.Value = string.IsNullOrWhiteSpace(department) || department == "All" ? DBNull.Value : $"%{department.Trim()}%"; 
                holCmd.Parameters.Add(pHolDept);

                using var holReader = await holCmd.ExecuteReaderAsync();
                while (await holReader.ReadAsync())
                {
                    holidays[holReader.GetString(1)] = (holReader.GetInt32(0), holReader.GetString(2));
                }
                await holReader.CloseAsync();

                // Fetch all active collection time slots (recurring + specific date)
                var allSlots = new List<SlotRecord>();
                using var slotCmd = conn.CreateCommand();
                slotCmd.CommandText = @"
                    SELECT s.""Id"", s.""DayOfWeek"", CAST(s.""StartTime"" AS varchar), CAST(s.""EndTime"" AS varchar),
                           s.""MaxCapacity"", s.""IsActive"", COALESCE(s.""DepartmentName"", 'General'),
                           CAST(s.""SpecificDate"" AS varchar)
                    FROM ""CollectionTimeSlots"" s
                    WHERE s.""IsActive"" = TRUE
                      AND (@dept IS NULL OR LOWER(s.""DepartmentName"") LIKE LOWER(@dept))
                    ORDER BY s.""DayOfWeek"", s.""StartTime"";";
                var pSlotDept = slotCmd.CreateParameter(); pSlotDept.ParameterName = "@dept"; 
                pSlotDept.Value = string.IsNullOrWhiteSpace(department) || department == "All" ? DBNull.Value : $"%{department.Trim()}%"; 
                slotCmd.Parameters.Add(pSlotDept);

                using var slotReader = await slotCmd.ExecuteReaderAsync();
                while (await slotReader.ReadAsync())
                {
                    allSlots.Add(new SlotRecord(
                        Id: slotReader.GetInt32(0),
                        DayOfWeek: slotReader.GetInt32(1),
                        StartTime: slotReader.GetString(2),
                        EndTime: slotReader.GetString(3),
                        MaxCapacity: slotReader.GetInt32(4),
                        IsActive: slotReader.GetBoolean(5),
                        DepartmentName: slotReader.GetString(6),
                        SpecificDate: slotReader.IsDBNull(7) ? null : slotReader.GetString(7)
                    ));
                }
                await slotReader.CloseAsync();

                // Fetch booking counts aggregated by BookedDate and StartTime for [today, endDate]
                var bookingsCountMap = new Dictionary<string, int>();
                using var bkCmd = conn.CreateCommand();
                bkCmd.CommandText = @"
                    SELECT CAST(b.""BookedDate"" AS varchar), " + CollectionSlotSql.BookingStartTime + @", COUNT(*)::int
                    FROM ""CollectionBookings"" b
                    WHERE b.""Status"" = 'Confirmed'
                      AND b.""BookedDate"" >= @today AND b.""BookedDate"" <= @endDate
                      AND (@dept IS NULL OR LOWER(b.""DepartmentName"") LIKE LOWER(@dept))
                    GROUP BY b.""BookedDate"", " + CollectionSlotSql.BookingStartTime + ";";
                var pBkToday = bkCmd.CreateParameter(); pBkToday.ParameterName = "@today"; pBkToday.Value = today; bkCmd.Parameters.Add(pBkToday);
                var pBkEnd = bkCmd.CreateParameter(); pBkEnd.ParameterName = "@endDate"; pBkEnd.Value = endDate; bkCmd.Parameters.Add(pBkEnd);
                var pBkDept = bkCmd.CreateParameter(); pBkDept.ParameterName = "@dept"; 
                pBkDept.Value = string.IsNullOrWhiteSpace(department) || department == "All" ? DBNull.Value : $"%{department.Trim()}%"; 
                bkCmd.Parameters.Add(pBkDept);

                using var bkReader = await bkCmd.ExecuteReaderAsync();
                while (await bkReader.ReadAsync())
                {
                    if (!bkReader.IsDBNull(0) && !bkReader.IsDBNull(1))
                    {
                        var key = $"{bkReader.GetString(0)}_{bkReader.GetString(1)}";
                        bookingsCountMap[key] = bkReader.GetInt32(2);
                    }
                }
                await bkReader.CloseAsync();

                // Assemble day-by-day chronologically sorted schedule starting from Today
                var schedule = new List<object>();

                for (int i = 0; i < days; i++)
                {
                    var date = today.AddDays(i);
                    var dateKey = date.ToString("yyyy-MM-dd");
                    int isoDow = (int)date.DayOfWeek == 0 ? 7 : (int)date.DayOfWeek;
                    string dayName = date.ToString("dddd");
                    bool isToday = (i == 0);

                    bool isDeclaredHoliday = holidays.ContainsKey(dateKey);
                    bool isSunday = (isoDow == 7);
                    bool isHoliday = isDeclaredHoliday || (isSunday && !allSlots.Any(s => s.SpecificDate == dateKey));
                    int? holidayId = isDeclaredHoliday ? holidays[dateKey].id : null;
                    string holidayReason = isDeclaredHoliday ? holidays[dateKey].reason : (isSunday ? "Sunday (Public Holiday)" : "");

                    // Slots: specific date slots take precedence; otherwise use recurring slots for this weekday
                    var dateSpecific = allSlots.Where(s => s.SpecificDate == dateKey).ToList();
                    var daySlots = dateSpecific.Count > 0
                        ? dateSpecific
                        : allSlots.Where(s => s.SpecificDate == null && s.DayOfWeek == isoDow).ToList();

                    var renderedSlots = new List<object>();
                    int totalCap = 0;
                    int totalBooked = 0;

                    if (!isHoliday)
                    {
                        foreach (var s in daySlots.OrderBy(s => s.StartTime))
                        {
                            var startHm = s.StartTime.Substring(0, 5);
                            var endHm = s.EndTime.Substring(0, 5);
                            TimeSpan.TryParse(s.StartTime, out var slotStartTime);
                            TimeSpan.TryParse(s.EndTime, out var slotEndTime);

                            var bKey = $"{dateKey}_{startHm}";
                            int booked = bookingsCountMap.TryGetValue(bKey, out int bCount) ? bCount : 0;
                            int remaining = Math.Max(0, s.MaxCapacity - booked);

                            bool isRealtimeActive = isToday && currentTime >= slotStartTime && currentTime < slotEndTime;
                            bool isSlotPast = isToday && currentTime >= slotEndTime;

                            string status = isRealtimeActive ? "Active Now" : (isSlotPast ? "Ended" : (remaining == 0 ? "Fully Booked" : "Open"));

                            totalCap += s.MaxCapacity;
                            totalBooked += booked;

                            renderedSlots.Add(new
                            {
                                slotId = s.Id,
                                departmentName = s.DepartmentName,
                                dayOfWeek = s.DayOfWeek,
                                specificDate = s.SpecificDate,
                                startTime = startHm,
                                endTime = endHm,
                                timeWindow = $"{startHm} - {endHm}",
                                maxCapacity = s.MaxCapacity,
                                bookedCount = booked,
                                remainingSpots = remaining,
                                isRealtimeActive = isRealtimeActive,
                                isPast = isSlotPast,
                                status = status
                            });
                        }
                    }

                    schedule.Add(new
                    {
                        date = dateKey,
                        dayOfWeek = isoDow,
                        dayName = dayName,
                        formattedDate = date.ToString("dddd, dd MMM yyyy"),
                        shortDate = date.ToString("dd MMM"),
                        isToday = isToday,
                        isHoliday = isHoliday,
                        holidayId = holidayId,
                        holidayReason = holidayReason,
                        totalCapacity = totalCap,
                        totalBooked = totalBooked,
                        remainingSpots = Math.Max(0, totalCap - totalBooked),
                        slotsCount = renderedSlots.Count,
                        slots = renderedSlots
                    });
                }

                return Ok(schedule);
            }
            catch (Exception ex)
            {
                return StatusCode(500, $"Database Error: {ex.Message}");
            }
            finally
            {
                if (wasClosed) await conn.CloseAsync();
            }
        }

